"""Extract libwebp's VP8 encoder constant tables from its C source into C# (no hand transcription).

Usage: python -I gen_vp8enc_tables.py <libwebp 1.6.0 src dir with the .c files flat> <output .cs>
Tables are flattened row-major; the C# names keep libwebp's names so the port can be read side by side.
"""
import re
import sys

SRC, OUT = sys.argv[1], sys.argv[2]

# (file, C name, C# element type)
WANTED = [
    ("cost.c", "VP8EntropyCost", "ushort"),
    ("cost.c", "VP8LevelFixedCosts", "ushort"),
    ("cost.c", "VP8EncBands", "byte"),
    ("cost_enc.c", "VP8LevelCodes", "ushort"),
    ("cost_enc.c", "VP8FixedCostsUV", "ushort"),
    ("cost_enc.c", "VP8FixedCostsI16", "ushort"),
    ("cost_enc.c", "VP8FixedCostsI4", "ushort"),
    ("tree_enc.c", "VP8CoeffsProba0", "byte"),
    ("tree_enc.c", "VP8CoeffsUpdateProba", "byte"),
    ("tree_enc.c", "kBModesProba", "byte"),
    ("quant_enc.c", "kZigzag", "byte"),
    ("quant_enc.c", "kDcTable", "byte"),
    ("quant_enc.c", "kAcTable", "ushort"),
    ("quant_enc.c", "kAcTable2", "ushort"),
    ("quant_enc.c", "kBiasMatrices", "byte"),
    ("quant_enc.c", "kFreqSharpening", "byte"),
    ("quant_enc.c", "kWeightY", "ushort"),
    ("filter_enc.c", "kLevelsFromDelta", "byte"),
    ("frame_enc.c", "VP8Cat3", "byte"),
    ("frame_enc.c", "VP8Cat4", "byte"),
    ("frame_enc.c", "VP8Cat5", "byte"),
    ("frame_enc.c", "VP8Cat6", "byte"),
    ("bit_writer_utils.c", "kNorm", "byte"),
    ("bit_writer_utils.c", "kNewRange", "byte"),
]


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


out = ["// <auto-generated> by scripts/images/gen_vp8enc_tables.py from libwebp 1.6.0 (BSD, see NOTICE.md). Do not edit.",
       "// Tables are flattened row-major; names are libwebp's.",
       "namespace SpawnDev.Codecs.Images.WebP.Lossy;", "",
       "internal static class Vp8EncTables", "{"]
for fn, name, cs in WANTED:
    text = strip_comments(open(f"{SRC}/{fn}", encoding="utf-8").read())
    m = re.search(r"\b" + re.escape(name) + r"\s*((?:\[[^\]]*\]\s*)+)=\s*\{", text)
    if not m:
        raise SystemExit(f"{name} not found in {fn}")
    i = m.end() - 1
    depth = 0
    j = i
    while True:
        c = text[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    body = text[i:j + 1]
    nums = re.findall(r"0x[0-9a-fA-F]+|\d+", body)
    vals = [int(x, 16) if x.startswith("0x") else int(x) for x in nums]
    dims = m.group(1).strip()
    rows = [", ".join(str(v) for v in vals[k:k + 16]) for k in range(0, len(vals), 16)]
    out.append(f"    /// <summary>libwebp {fn}: {name}{dims} ({len(vals)} values).</summary>")
    out.append(f"    internal static readonly {cs}[] {name} =")
    out.append("    {")
    for r in rows:
        out.append(f"        {r},")
    out.append("    };")
    out.append("")
out.append("}")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote", OUT)
