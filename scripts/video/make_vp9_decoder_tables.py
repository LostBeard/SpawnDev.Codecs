"""Generate SpawnDev.Codecs/Video/Vp9/Decoder/Vp9DecoderTables.cs from libvpx v1.17.0 (BSD-3-Clause).

Usage: make_vp9_decoder_tables.py <libvpx src dir> <libvpx_ref -c dump of a stream whose first frame is a key frame>
                                  <output .cs>
- DefaultFrameContext: the 2039 probability bytes of libvpx's FRAME_CONTEXT right after vp9_setup_past_independence
  (stage-0 record of the first key frame = vp9_default_coef_probs + init_mode_probs + vp9_init_mv_probs).
- InvMapTable: vp9/decoder/vp9_dsubexp.c inv_map_table.
"""
import re, sys

CTX = 2039


def c_array(path, name):
    """Integers of the C array initializer `name[...] = { ... };` in path (comments stripped)."""
    text = open(path, encoding="utf-8", errors="replace").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^\]]*\]\s*)+=\s*\{", text)
    assert m, f"{name} not found in {path}"
    depth, i = 1, m.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return [int(v, 0) for v in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", text[m.end():i - 1])]


def cs_bytes(name, values, doc):
    lines = [f"    /// <summary>{doc}</summary>", f"    public static readonly byte[] {name} =", "    {"]
    for i in range(0, len(values), 24):
        lines.append("        " + ", ".join(str(v) for v in values[i:i + 24]) + ",")
    lines.append("    };")
    return "\n".join(lines)


src, dump, out = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(dump, "rb").read()
assert data[0] == 0, "first record must be stage 0"
default_ctx = list(data[1:1 + CTX])
inv_map = c_array(src + "/vp9/decoder/vp9_dsubexp.c", "inv_map_table")
assert len(inv_map) == 255, len(inv_map)  # MAX_PROB entries

body = f"""// <auto-generated> scripts/video/make_vp9_decoder_tables.py from libvpx v1.17.0 (BSD-3-Clause, see NOTICE.md).
// Do not edit by hand.

namespace SpawnDev.Codecs.Video.Vp9.Decoder;

/// <summary>Constant tables of the VP9 decoder (libvpx v1.17.0).</summary>
internal static class Vp9DecoderTables
{{
{cs_bytes("DefaultFrameContext", default_ctx, "libvpx FRAME_CONTEXT defaults (vp9_setup_past_independence), 2039 bytes in struct order (see Vp9Ctx).")}

{cs_bytes("InvMapTable", inv_map, "vp9_dsubexp.c inv_map_table (vp9_diff_update_prob).")}
}}
"""
open(out, "w", encoding="utf-8", newline="\n").write(body)
print("wrote", out)
