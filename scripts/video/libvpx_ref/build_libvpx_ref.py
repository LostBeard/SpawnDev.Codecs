"""Build libvpx_ref.exe: libvpx's VP9 decoder (BSD-3-Clause) as plain C with MSVC, the reference for our VP9 decoder.

Usage: py -3 build_libvpx_ref.py <libvpx source dir> <build dir> [extra .c files ...]

libvpx is not in this repository: clone it (we use tag v1.17.0) and pass its folder. The script writes the generated
headers libvpx's configure would write (vpx_config.h for a "generic" C target, single thread, 8-bit; vpx_version.h; the
rtcd headers from build/make/rtcd.pl with --arch=generic, which needs perl on PATH) into the build dir, then compiles
the decoder sources plus libvpx_ref.c with cl.exe from the newest Visual Studio's vcvars64.bat. Extra .c files (e.g. an
instrumented copy of a libvpx file) replace the libvpx file of the same name.
"""
import glob, os, re, subprocess, sys

src, build = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
extra = [os.path.abspath(p) for p in sys.argv[3:]]
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(build, exist_ok=True)

ENABLED = {"CONFIG_VP9", "CONFIG_VP9_DECODER", "CONFIG_DECODERS", "CONFIG_OS_SUPPORT", "CONFIG_STATIC",
           "CONFIG_MSVS", "HAVE_VPX_PORTS"}

# every CONFIG_ / HAVE_ / ARCH_ symbol the sources test; all 0 but the set above (plain C, no SIMD, no threads)
symbols = set()
for d in ("vp9", "vpx", "vpx_dsp", "vpx_mem", "vpx_scale", "vpx_util", "vpx_ports"):
    for path in glob.glob(os.path.join(src, d, "**", "*.[ch]"), recursive=True):
        symbols |= set(re.findall(r"\b((?:CONFIG|HAVE|VPX_ARCH|ARCH)_[A-Z0-9_]+)\b", open(path, errors="replace").read()))
symbols |= ENABLED
# derived inside libvpx headers and tested with defined(): must stay undefined (vpx_util/endian_inl.h)
symbols = {s for s in symbols if not s.startswith("HAVE_BUILTIN_")}
with open(os.path.join(build, "vpx_config.h"), "w") as f:
    f.write("/* generated by build_libvpx_ref.py: generic C, single thread, 8-bit VP9 decoder */\n")
    f.write("#ifndef VPX_CONFIG_H\n#define VPX_CONFIG_H\n#define RESTRICT\n#define INLINE __inline\n")
    for s in sorted(symbols):
        f.write(f"#define {s} {1 if s in ENABLED else 0}\n")
    f.write("#endif\n")
with open(os.path.join(build, "vpx_config.c"), "w") as f:
    f.write('#include "vpx/vpx_codec.h"\nstatic const char *cfg = "generic (build_libvpx_ref.py)";\n'
            "const char *vpx_codec_build_config(void) { return cfg; }\n")
with open(os.path.join(build, "vpx_version.h"), "w") as f:
    f.write("#define VERSION_MAJOR 1\n#define VERSION_MINOR 17\n#define VERSION_PATCH 0\n#define VERSION_EXTRA \"\"\n"
            "#define VERSION_PACKED ((VERSION_MAJOR << 16) | (VERSION_MINOR << 8) | (VERSION_PATCH))\n"
            '#define VERSION_STRING_NOSP "v1.17.0"\n#define VERSION_STRING " v1.17.0"\n')
mk = os.path.join(build, "vpx_config.mk")
# LF only: rtcd.pl chomps "\n" alone, so CRLF made every value read as "yes" + CR, which never equals "yes"
with open(mk, "w", newline="\n") as f:
    for s in sorted(symbols):
        if s.startswith(("CONFIG_", "HAVE_")):
            f.write(f"{s}={'yes' if s in ENABLED else 'no'}\n")
for sym, defs in (("vp9_rtcd", "vp9/common/vp9_rtcd_defs.pl"), ("vpx_dsp_rtcd", "vpx_dsp/vpx_dsp_rtcd_defs.pl"),
                  ("vpx_scale_rtcd", "vpx_scale/vpx_scale_rtcd.pl")):
    out = subprocess.run(["perl", os.path.join(src, "build", "make", "rtcd.pl"), "--arch=generic", f"--sym={sym}",
                          f"--config={mk}", os.path.join(src, defs)], capture_output=True, text=True, check=True).stdout
    open(os.path.join(build, sym + ".h"), "w").write(out)

# Instrumentation: copies of libvpx files with hook calls inserted (each insertion point must occur exactly once).
# libvpx_ref.c defines the hook; it is called with the decoder and a stage number.
HOOK_DECL = "struct VP9Decoder;\nextern void (*vp9ref_hook)(struct VP9Decoder *pbi, int stage);\n"
PATCHES = {
    "vp9/decoder/vp9_decodeframe.c": [
        # stage 0: the frame context this frame loads; stage 1: after the compressed header's updates
        ("  *cm->fc = cm->frame_contexts[cm->frame_context_idx];\n",
         "  *cm->fc = cm->frame_contexts[cm->frame_context_idx];\n  if (vp9ref_hook) vp9ref_hook(pbi, 0);\n"),
        ("  new_fb->corrupted = read_compressed_header(pbi, data, first_partition_size);\n",
         "  new_fb->corrupted = read_compressed_header(pbi, data, first_partition_size);\n"
         "  if (vp9ref_hook) vp9ref_hook(pbi, 1);\n"),
        # stage 2: all tiles decoded (mode info, counts), before backward adaptation; stage 3: after adaptation
        ("  if (!xd->corrupted) {\n    if (!cm->error_resilient_mode && !cm->frame_parallel_decoding_mode) {\n",
         "  if (vp9ref_hook) vp9ref_hook(pbi, 2);\n"
         "  if (!xd->corrupted) {\n    if (!cm->error_resilient_mode && !cm->frame_parallel_decoding_mode) {\n"),
        ("  // Non frame parallel update frame context here.\n",
         "  if (vp9ref_hook) vp9ref_hook(pbi, 3);\n  // Non frame parallel update frame context here.\n"),
        # the loop filter runs once over the whole frame after all tiles (instead of row by row inside
        # decode_tiles), so stage 4 sees the reconstructed frame before it and stage 5 after it. libvpx's own MT path
        # filters after the tiles too; check_vectors.py proves the output unchanged.
        ("      if (cm->lf.filter_level && !cm->skip_loop_filter) {\n        const int lf_start = mi_row - MI_BLOCK_SIZE;\n",
         "      if (0) {\n        const int lf_start = mi_row - MI_BLOCK_SIZE;\n"),
        ("  if (cm->lf.filter_level && !cm->skip_loop_filter) {\n    LFWorkerData *const lf_data = (LFWorkerData *)pbi->lf_worker.data1;\n"
         "    winterface->sync(&pbi->lf_worker);\n    lf_data->start = lf_data->stop;\n",
         "  if (0) {\n    LFWorkerData *const lf_data = (LFWorkerData *)pbi->lf_worker.data1;\n"
         "    winterface->sync(&pbi->lf_worker);\n    lf_data->start = lf_data->stop;\n"),
        ("    *p_data_end = decode_tiles(pbi, data + first_partition_size, data_end);\n",
         "    *p_data_end = decode_tiles(pbi, data + first_partition_size, data_end);\n"
         "    if (vp9ref_hook) vp9ref_hook(pbi, 4);\n"
         "    if (cm->lf.filter_level && !cm->skip_loop_filter)\n"
         "      vp9_loop_filter_frame(new_fb, cm, &pbi->mb, cm->lf.filter_level, 0, 0);\n"
         "    if (vp9ref_hook) vp9ref_hook(pbi, 5);\n"),
    ],
}
patched = []
for rel, edits in PATCHES.items():
    text = open(os.path.join(src, rel), newline="").read().replace("\r\n", "\n")   # a Windows clone may be CRLF
    first_include = text.index("#include")
    text = text[:first_include] + HOOK_DECL + text[first_include:]
    for old, new in edits:
        assert text.count(old) == 1, f"{rel}: insertion point occurs {text.count(old)} times: {old!r}"
        text = text.replace(old, new)
    out = os.path.join(build, "patched_" + os.path.basename(rel))
    open(out, "w", newline="").write(text)
    patched.append((os.path.basename(rel), out))

sources = []
for pattern in ("vp9/common/*.c", "vp9/decoder/*.c", "vp9/vp9_dx_iface.c", "vp9/vp9_iface_common.c", "vpx_dsp/*.c", "vpx/src/vpx_codec.c",
                "vpx/src/vpx_decoder.c", "vpx/src/vpx_image.c", "vpx_mem/vpx_mem.c", "vpx_scale/generic/*.c",
                "vpx_scale/vpx_scale_rtcd.c", "vpx_util/vpx_thread.c", "md5_utils.c"):
    sources += glob.glob(os.path.join(src, pattern))
# not in a decoder-only build (libvpx's .mk files gate them on VP9_POSTPROC / VP9_ENCODER / SPATIAL_RESAMPLING)
EXCLUDED = {"vp9_mfqe.c", "vp9_postproc.c", "variance.c", "vpx_scale.c", "gen_scalers.c", "psnr.c", "psnrhvs.c",
            "ssim.c"}
by_name = {os.path.basename(p): p for p in sources if os.path.basename(p) not in EXCLUDED}
for name, path in patched:
    by_name[name] = path
for p in extra:
    by_name[os.path.basename(p)] = p
sources = sorted(by_name.values()) + [os.path.join(build, "vpx_config.c"), os.path.join(here, "libvpx_ref.c")]

vcvars = sorted(glob.glob(r"C:\Program Files\Microsoft Visual Studio\*\*\VC\Auxiliary\Build\vcvars64.bat"))[-1]
rsp = os.path.join(build, "cl.rsp")
with open(rsp, "w") as f:
    f.write("/nologo /O2 /W0 /MP /DNDEBUG /D_CRT_SECURE_NO_WARNINGS\n")
    f.write(f'/I"{build}" /I"{src}"\n')
    f.write(f'/Fo"{build}\\\\" /Fe"{os.path.join(build, "libvpx_ref.exe")}"\n')
    for s in sources:
        f.write(f'"{s}"\n')
bat = os.path.join(build, "build.bat")
with open(bat, "w") as f:
    f.write(f'@call "{vcvars}" >nul\r\ncl @"{rsp}"\r\n')
r = subprocess.run(["cmd", "/c", bat], capture_output=True, text=True)
errors = [l for l in r.stdout.splitlines() if ": error" in l or "fatal error" in l or "LNK" in l]
print("\n".join(errors[:40]))
print("build", "OK" if r.returncode == 0 else f"FAILED ({r.returncode})", os.path.join(build, "libvpx_ref.exe"))
sys.exit(r.returncode)
