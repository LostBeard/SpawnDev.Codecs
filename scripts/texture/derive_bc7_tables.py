"""BC7 partition and anchor tables, read back from a reference decoder (no hand-typed tables).

usage: python derive_bc7_tables.py <out.cs>

Mode 1 (2 subsets) and mode 2 (3 subsets) blocks are crafted per partition:
  - membership: every subset gets its own flat colour (all indices 0), so each pixel's colour names its subset;
  - anchors: every index bit is 1; an anchor index has one bit fewer, so anchor pixels decode to a different colour.
texture2ddecoder decodes them (Pillow's decoder must agree), and the tables are written as C# arrays.
"""
import io, sys
import numpy as np
import texture2ddecoder as t2d


class Bits:
    def __init__(self):
        self.v = 0
        self.n = 0

    def put(self, value, count):
        self.v |= (value & ((1 << count) - 1)) << self.n
        self.n += count

    def block(self):
        assert self.n == 128, self.n
        return self.v.to_bytes(16, "little")


def decode(block):
    out = np.frombuffer(t2d.decode_bc7(block, 4, 4), np.uint8).reshape(4, 4, 4)
    return out[..., [2, 1, 0, 3]].reshape(16, 4)


def mode1(partition, ends, index_bit, anchors):
    """ends: per subset (e0, e1) 6-bit grey levels; index_bit: 0 or 1 for every index bit."""
    b = Bits()
    b.put(0b10, 2)               # mode 1: bit 1 set (LSB first: 0 then 1)
    b.put(partition, 6)
    for _ch in range(3):
        for s in range(2):
            b.put(ends[s][0], 6)
            b.put(ends[s][1], 6)
    b.put(0, 2)                  # shared p-bits
    for p in range(16):
        b.put((1 << 3) - 1 if index_bit else 0, 2 if p in anchors else 3)
    return b.block()


def mode2(partition, ends, index_bit, anchors):
    b = Bits()
    b.put(0b100, 3)              # mode 2
    b.put(partition, 6)
    for _ch in range(3):
        for s in range(3):
            b.put(ends[s][0], 5)
            b.put(ends[s][1], 5)
    for p in range(16):
        b.put(3 if index_bit else 0, 1 if p in anchors else 2)
    return b.block()


def main():
    p2, a2, p3, a3a, a3b = [], [], [], [], []
    for part in range(64):
        # membership (anchors do not matter with all-zero indices: pass a guess)
        px = decode(mode1(part, [(0, 0), (63, 63)], 0, {0, 15}))
        subsets = [0 if px[i, 0] < 128 else 1 for i in range(16)]
        assert subsets[0] == 0
        # anchor: the subset-1 pixel whose all-ones index decodes differently; find it by trying every candidate
        found = None
        for cand in range(16):
            if subsets[cand] != 1:
                continue
            px = decode(mode1(part, [(0, 63), (0, 63)], 1, {0, cand}))
            # with the right anchor every subset-1 pixel but the anchor decodes to index 7 (the brightest)
            vals = [px[i, 0] for i in range(16) if subsets[i] == 1]
            if sum(1 for i in range(16) if subsets[i] == 1 and px[i, 0] != max(vals)) == 1 and px[cand, 0] != max(vals):
                found = cand
                break
        assert found is not None, part
        p2 += subsets
        a2.append(found)

    for part in range(64):
        px = decode(mode2(part, [(0, 0), (15, 15), (31, 31)], 0, {0, 1, 2}))
        subsets = []
        for i in range(16):
            v = px[i, 0]
            subsets.append(0 if v < 64 else (1 if v < 192 else 2))
        assert subsets[0] == 0
        found = None
        for c1 in range(16):
            if subsets[c1] != 1:
                continue
            for c2 in range(16):
                if subsets[c2] != 2:
                    continue
                px = decode(mode2(part, [(0, 31), (0, 31), (0, 31)], 1, {0, c1, c2}))
                top = max(px[i, 0] for i in range(16))
                lows = [i for i in range(16) if px[i, 0] != top]
                if sorted(lows) == sorted([0, c1, c2]):
                    found = (c1, c2)
                    break
            if found:
                break
        assert found is not None, part
        p3 += subsets
        a3a.append(found[0])
        a3b.append(found[1])

    def arr(name, vals, per_line=32):
        lines = []
        for i in range(0, len(vals), per_line):
            lines.append("        " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
        return f"    internal static readonly byte[] {name} =\n    {{\n" + "\n".join(lines) + "\n    };\n"

    cs = ("// SpawnDev.Codecs is licensed under MIT (see LICENSE.txt).\n"
          "//\n"
          "// GENERATED by scripts/texture/derive_bc7_tables.py: BC7's partition and anchor tables (the D3D / BPTC spec tables),\n"
          "// read back from a reference decoder with crafted mode 1 and mode 2 blocks. Do not edit by hand.\n\n"
          "namespace SpawnDev.Codecs.Images.Texture;\n\n"
          "internal static class Bc7Tables\n{\n"
          "    /// <summary>2-subset partitions: subset of pixel p of partition n at [n * 16 + p].</summary>\n"
          + arr("Partition2", p2) +
          "\n    /// <summary>2-subset partitions: the anchor pixel of subset 1 (subset 0's is pixel 0).</summary>\n"
          + arr("Anchor2", a2) +
          "\n    /// <summary>3-subset partitions: subset of pixel p of partition n at [n * 16 + p].</summary>\n"
          + arr("Partition3", p3) +
          "\n    /// <summary>3-subset partitions: the anchor pixel of subset 1.</summary>\n"
          + arr("Anchor3Second", a3a) +
          "\n    /// <summary>3-subset partitions: the anchor pixel of subset 2.</summary>\n"
          + arr("Anchor3Third", a3b) +
          "}\n")
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write(cs)
    print("written", sys.argv[1], "anchors2 sample", a2[:8], "anchors3", a3a[:4], a3b[:4])


if __name__ == "__main__":
    main()
