"""Copy etcpak's DXTC colour division table into C# (no hand-typed table).

usage: python extract_etcpak_tables.py <etcpak src/etcpak/ProcessDxtc.cpp> <out.cs>

etcpak (https://github.com/wolfpld/etcpak), BSD 3-clause, Copyright (c) 2013-2026, Bartosz Taudul: the tables are copied
from the version the Python package etcpak 0.9.15 builds (its sdist), the encoder our identity tests compare against.
"""
import re, sys


def table(src, name):
    m = re.search(r"static const uint16_t " + re.escape(name) + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S)
    assert m, name
    vals = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(1))]
    return vals


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    div = table(src, "DivTable")

    def arr(name, vals, per_line=16):
        lines = ["        " + ", ".join(f"0x{v:04x}" for v in vals[i:i + per_line]) + "," for i in range(0, len(vals), per_line)]
        return f"    internal static readonly ushort[] {name} =\n    {{\n" + "\n".join(lines) + "\n    };\n"

    cs = ("// SpawnDev.Codecs is licensed under MIT (see LICENSE.txt).\n"
          "//\n"
          "// GENERATED by scripts/texture/extract_etcpak_tables.py from etcpak's ProcessDxtc.cpp (etcpak 0.9.15). Do not edit.\n"
          "// etcpak (https://github.com/wolfpld/etcpak): Copyright (c) 2013-2026, Bartosz Taudul <wolf@nereid.pl>, BSD 3-clause\n"
          "// license, reproduced in NOTICE.md.\n\n"
          "namespace SpawnDev.Codecs.Images.Texture;\n\n"
          "internal static class EtcpakDxtcTables\n{\n"
          "    /// <summary>BC1 colour: etcpak's reciprocals, indexed by the summed RGB range of the block (0 .. 765).</summary>\n"
          + arr("DivTable", div) +
          "}\n")
    with open(sys.argv[2], "w", newline="\n") as f:
        f.write(cs)
    print("DivTable", len(div), div[:6])


if __name__ == "__main__":
    main()
