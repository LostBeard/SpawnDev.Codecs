"""Copy bc7enc's static tables into C# (no hand-typed tables).

usage: python extract_bc7enc_tables.py <etcpak src/etcpak/bc7enc.cpp> <out.cs>

bc7enc (Richard Geldreich, Jr., MIT or public domain), the copy etcpak 0.9.15 builds: the least-squares weight tables,
the partition search order and the partition predictors.
"""
import re, sys


def block(src, decl):
    i = src.index(decl)
    j = src.index("{", i)
    k = src.index("};", j)
    return src[j + 1:k]


def nums(text, kind):
    if kind == "float":
        return [v for v in re.findall(r"-?\d+\.\d+f?", text)]
    return re.findall(r"0x[0-9a-fA-F]+|\d+", text)


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    w2x = nums(block(src, "static const float g_bc7_weights2x"), "float")
    w3x = nums(block(src, "static const float g_bc7_weights3x"), "float")
    w4x = nums(block(src, "static const float g_bc7_weights4x"), "float")
    assert (len(w2x), len(w3x), len(w4x)) == (16, 32, 64), (len(w2x), len(w3x), len(w4x))

    order_text = block(src, "static const uint8_t s_sorted_partition_order[64]")
    order = [int(a) - int(b) for a, b in re.findall(r"(\d+)\s*-\s*(\d+)", order_text)]
    assert len(order) == 64 and sorted(order) == list(range(64)), order

    pred_text = block(src, "static const uint32_t g_partition_predictors[35]")
    preds = []
    for entry in pred_text.split(","):
        entry = entry.strip()
        if not entry:
            continue
        if entry == "UINT32_MAX":
            preds.append(0xFFFFFFFF)
        else:
            v = 0
            for bit in re.findall(r"1\s*<<\s*(\d+)", entry):
                v |= 1 << int(bit)
            preds.append(v)
    assert len(preds) == 35, len(preds)

    def farr(name, vals):
        lines = ["        " + ", ".join(v if v.endswith("f") else v + "f" for v in vals[i:i + 8]) + "," for i in range(0, len(vals), 8)]
        return f"    internal static readonly float[] {name} =\n    {{\n" + "\n".join(lines) + "\n    };\n"

    def iarr(name, vals, typ, fmt):
        lines = ["        " + ", ".join(fmt(v) for v in vals[i:i + 8]) + "," for i in range(0, len(vals), 8)]
        return f"    internal static readonly {typ}[] {name} =\n    {{\n" + "\n".join(lines) + "\n    };\n"

    cs = ("// SpawnDev.Codecs is licensed under MIT (see LICENSE.txt).\n"
          "//\n"
          "// GENERATED by scripts/texture/extract_bc7enc_tables.py from bc7enc.cpp (Richard Geldreich, Jr., MIT or public domain;\n"
          "// the copy etcpak 0.9.15 builds; see NOTICE.md). Do not edit by hand.\n\n"
          "namespace SpawnDev.Codecs.Images.Texture;\n\n"
          "internal static class Bc7EncTables\n{\n"
          "    /// <summary>Per 2-bit weight: w * w, (1 - w) * w, (1 - w) * (1 - w), w (least squares).</summary>\n"
          + farr("Weights2x", w2x) +
          "\n    /// <summary>Per 3-bit weight: w * w, (1 - w) * w, (1 - w) * (1 - w), w.</summary>\n"
          + farr("Weights3x", w3x) +
          "\n    /// <summary>Per 4-bit weight: w * w, (1 - w) * w, (1 - w) * (1 - w), w.</summary>\n"
          + farr("Weights4x", w4x) +
          "\n    /// <summary>2-subset partitions in the order bc7enc's estimator scans them (most used first).</summary>\n"
          + iarr("SortedPartitionOrder", order, "byte", str) +
          "\n    /// <summary>Partitions 0..34: the key partitions (bit k + 1) that must win the first 14 for it to be scanned.</summary>\n"
          + iarr("PartitionPredictors", preds, "uint", lambda v: f"0x{v:08X}u") +
          "}\n")
    with open(sys.argv[2], "w", newline="\n") as f:
        f.write(cs)
    print("weights", len(w2x), len(w3x), len(w4x), "order", order[:8], "predictors", [hex(p) for p in preds[:6]])


if __name__ == "__main__":
    main()
