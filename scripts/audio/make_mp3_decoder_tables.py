"""The MP3 decoder's tables, copied from minimp3 (minimp3.h, CC0 / public domain, github.com/lieff/minimp3) verbatim:
scalefactor band widths, scalefactor partitions, the Huffman decoding tables, pow(x, 4/3) for small x, the quarter-step
exponent fractions, intensity stereo pans, alias reduction, IMDCT twiddles and windows, the synthesis DCT secants and
window. Float values keep minimp3's decimal literals (C and C# both round a decimal literal to the nearest float), so the
tables are bit-identical with minimp3's.

Writes SpawnDev.Codecs/Audio/Mp3/Mp3DecodeTables.cs.

Usage: python -I make_mp3_decoder_tables.py <path to minimp3.h>
"""
import os
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "SpawnDev.Codecs", "Audio", "Mp3", "Mp3DecodeTables.cs"))


def array(name, row=None):
    """The initializer tokens of `static const <type> name[...] = {...};`, rows zero-padded to `row` entries."""
    m = re.search(r"static const (?:float|int16_t|uint8_t) " + name + r"(?:\[[^\]]*\])+\s*=\s*\{(.*?)\};", src, re.S)
    assert m, name
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    groups = re.findall(r"\{([^{}]*)\}", body) if "{" in body else [body]
    out = []
    for g in groups:
        toks = [t.strip() for t in g.replace("\n", " ").split(",") if t.strip()]
        if row is not None:
            assert len(toks) <= row, (name, len(toks))
            toks += ["0"] * (row - len(toks))
        out += toks
    return out


def as_float(t):
    return t if t.endswith("f") else t + "f"


FLOATS = [
    ("ExpFrac", array("g_expfrac")),
    ("Pow43", array("g_pow43")),
    ("Pan", array("g_pan")),
    ("Aa", array("g_aa", 8)),
    ("Twid9", array("g_twid9")),
    ("Twid3", array("g_twid3")),
    ("MdctWindow", array("g_mdct_window", 18)),
    ("Sec", array("g_sec")),
    ("Win", array("g_win")),
]
INTS = [
    ("ScfLong", array("g_scf_long", 23)),
    ("ScfShort", array("g_scf_short", 40)),
    ("ScfMixed", array("g_scf_mixed", 40)),
    ("ScfPartitions", array("g_scf_partitions", 28)),
    ("ScfcDecode", array("g_scfc_decode")),
    ("Mod", array("g_mod")),
    ("Preamp", array("g_preamp")),
    ("Tabs", array("tabs")),
    ("Tab32", array("tab32")),
    ("Tab33", array("tab33")),
    ("TabIndex", array("tabindex")),
    ("Linbits", array("g_linbits")),
    ("HalfRate", array("halfrate", 15)),
]
EXPECT = {"ExpFrac": 4, "Pow43": 145, "Pan": 14, "Aa": 16, "Twid9": 18, "Twid3": 6, "MdctWindow": 36, "Sec": 24, "Win": 240,
          "ScfLong": 184, "ScfShort": 320, "ScfMixed": 320, "ScfPartitions": 84, "ScfcDecode": 16, "Mod": 24, "Preamp": 10,
          "Tab32": 28, "Tab33": 16, "TabIndex": 32, "Linbits": 32, "HalfRate": 90}
for name, vals in FLOATS + INTS:
    if name in EXPECT:
        assert len(vals) == EXPECT[name], (name, len(vals))


def emit(kind, items, fmt):
    lines, consts, at = [], [], 0
    for name, vals in items:
        consts.append(f"{kind}{name} = {at}")
        lines.append(f"        // {name} [{at}..{at + len(vals)})")
        for i in range(0, len(vals), 16):
            lines.append("        " + ", ".join(fmt(v) for v in vals[i:i + 16]) + ",")
        at += len(vals)
    return consts, lines, at


fc, fl, fn = emit("F", FLOATS, as_float)
ic, il, inn = emit("I", INTS, lambda t: t)

with open(OUT, "w", newline="\n", encoding="utf-8") as f:
    f.write("""// SpawnDev.Codecs is licensed under MIT (see LICENSE.txt). See NOTICE.md for upstream attributions.
//
// GENERATED by scripts/audio/make_mp3_decoder_tables.py from minimp3.h (port of minimp3, CC0 / public domain,
// github.com/lieff/minimp3). Do not edit by hand. The MP3 decoder's tables, minimp3's values verbatim (float literals
// as minimp3 writes them, so every value is the same float): uploaded once as two views (floats, ints).

namespace SpawnDev.Codecs.Audio.Mp3;

/// <summary>The MP3 decoder's tables (port of minimp3, CC0; see the file header).</summary>
internal static class Mp3DecodeTables
{
""")
    f.write("    /// <summary>Offsets into <see cref=\"Floats\"/>.</summary>\n")
    f.write("    public const int " + ", ".join(fc) + f", FloatCount = {fn};\n\n")
    f.write("    /// <summary>Offsets into <see cref=\"Ints\"/>.</summary>\n")
    f.write("    public const int " + ", ".join(ic) + f", IntCount = {inn};\n\n")
    f.write("    /// <summary>Float tables.</summary>\n    public static readonly float[] Floats =\n    {\n")
    f.write("\n".join(fl) + "\n    };\n\n")
    f.write("    /// <summary>Int tables.</summary>\n    public static readonly int[] Ints =\n    {\n")
    f.write("\n".join(il) + "\n    };\n}\n")
print(f"{OUT}: {fn} floats, {inn} ints")
