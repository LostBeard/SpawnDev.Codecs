    /// <summary>
    /// Look up the inverse-scan table for a given transform size and
    /// scan flavor. 32x32 only has the default flavor; passing Row or
    /// Col at 32x32 still returns the default table (libvpx never
    /// triggers those code paths at that size).
    /// </summary>
    public static ushort[] GetIscan(Vp9TxSize txSize, Vp9ScanType scanType)
    {
        return txSize switch
        {
            Vp9TxSize.Tx4x4 => scanType switch
            {
                Vp9ScanType.Row => RowIscan4x4,
                Vp9ScanType.Col => ColIscan4x4,
                _ => DefaultIscan4x4,
            },
            Vp9TxSize.Tx8x8 => scanType switch
            {
                Vp9ScanType.Row => RowIscan8x8,
                Vp9ScanType.Col => ColIscan8x8,
                _ => DefaultIscan8x8,
            },
            Vp9TxSize.Tx16x16 => scanType switch
            {
                Vp9ScanType.Row => RowIscan16x16,
                Vp9ScanType.Col => ColIscan16x16,
                _ => DefaultIscan16x16,
            },
            Vp9TxSize.Tx32x32 => DefaultIscan32x32,
            _ => throw new ArgumentOutOfRangeException(nameof(txSize)),
        };
    }
