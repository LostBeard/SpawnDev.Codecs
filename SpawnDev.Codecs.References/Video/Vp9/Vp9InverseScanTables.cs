// VP9 inverse scan-order tables - bit-exact copy of libvpx
// vp9/common/vp9_scan.c.
//
// The forward scan tables (slice 135's Vp9ScanTables) map
// scan-position to raster-position. iscan is the inverse map:
// `iscan[raster_pos]` = scan_position_of_raster_pos + 1. The +1
// offset matters because libvpx stores iscan values as int16_t and
// uses 0 as a sentinel for "this raster slot has no coefficient";
// the iscan-driven coefficient decode loop checks `iscan[raster] >=
// eob` to terminate at the end-of-block boundary, where `eob` is
// the count of decoded non-zero coefficients (one-based).
//
// Three flavors at 4x4 / 8x8 / 16x16 (default / row / col) plus the
// default-only 32x32 - the same shape as forward scans.
//
// Provenance: extracted directly from libvpx vp9_scan.c via raw
// text fetch + awk pipeline; counts verified at 16 / 64 / 256 /
// 1024 entries before commit.

