        bf1[30] = Btf(cospi[34], bf0[17], cospi[30], bf0[30]);
        bf1[31] = Btf(cospi[2], bf0[16], cospi[62], bf0[31]);
        bf1[32] = bf0[32] + bf0[33];
        bf1[33] = bf0[32] - bf0[33];
        bf1[34] = -bf0[34] + bf0[35];
        bf1[35] = bf0[34] + bf0[35];
        bf1[36] = bf0[36] + bf0[37];
        bf1[37] = bf0[36] - bf0[37];
        bf1[38] = -bf0[38] + bf0[39];
        bf1[39] = bf0[38] + bf0[39];
        bf1[40] = bf0[40] + bf0[41];
        bf1[41] = bf0[40] - bf0[41];
        bf1[42] = -bf0[42] + bf0[43];
        bf1[43] = bf0[42] + bf0[43];
        bf1[44] = bf0[44] + bf0[45];
        bf1[45] = bf0[44] - bf0[45];
        bf1[46] = -bf0[46] + bf0[47];
        bf1[47] = bf0[46] + bf0[47];
        bf1[48] = bf0[48] + bf0[49];
        bf1[49] = bf0[48] - bf0[49];
        bf1[50] = -bf0[50] + bf0[51];
        bf1[51] = bf0[50] + bf0[51];
        bf1[52] = bf0[52] + bf0[53];
        bf1[53] = bf0[52] - bf0[53];
        bf1[54] = -bf0[54] + bf0[55];
        bf1[55] = bf0[54] + bf0[55];
        bf1[56] = bf0[56] + bf0[57];
        bf1[57] = bf0[56] - bf0[57];
        bf1[58] = -bf0[58] + bf0[59];
        bf1[59] = bf0[58] + bf0[59];
        bf1[60] = bf0[60] + bf0[61];
        bf1[61] = bf0[60] - bf0[61];
        bf1[62] = -bf0[62] + bf0[63];
        bf1[63] = bf0[62] + bf0[63];

        // Stage 4.
        for (int i = 0; i < 8; i++) bf0[i] = bf1[i];
        bf0[8] = Btf(cospi[60], bf1[8], -cospi[4], bf1[15]);
        bf0[9] = Btf(cospi[28], bf1[9], -cospi[36], bf1[14]);
        bf0[10] = Btf(cospi[44], bf1[10], -cospi[20], bf1[13]);
        bf0[11] = Btf(cospi[12], bf1[11], -cospi[52], bf1[12]);
        bf0[12] = Btf(cospi[52], bf1[11], cospi[12], bf1[12]);
        bf0[13] = Btf(cospi[20], bf1[10], cospi[44], bf1[13]);
        bf0[14] = Btf(cospi[36], bf1[9], cospi[28], bf1[14]);
        bf0[15] = Btf(cospi[4], bf1[8], cospi[60], bf1[15]);
        bf0[16] = bf1[16] + bf1[17];
        bf0[17] = bf1[16] - bf1[17];
        bf0[18] = -bf1[18] + bf1[19];
        bf0[19] = bf1[18] + bf1[19];
        bf0[20] = bf1[20] + bf1[21];
        bf0[21] = bf1[20] - bf1[21];
        bf0[22] = -bf1[22] + bf1[23];
        bf0[23] = bf1[22] + bf1[23];
        bf0[24] = bf1[24] + bf1[25];
        bf0[25] = bf1[24] - bf1[25];
        bf0[26] = -bf1[26] + bf1[27];
        bf0[27] = bf1[26] + bf1[27];
        bf0[28] = bf1[28] + bf1[29];
        bf0[29] = bf1[28] - bf1[29];
        bf0[30] = -bf1[30] + bf1[31];
        bf0[31] = bf1[30] + bf1[31];
        bf0[32] = bf1[32];
        bf0[33] = Btf(-cospi[4], bf1[33], cospi[60], bf1[62]);
        bf0[34] = Btf(-cospi[60], bf1[34], -cospi[4], bf1[61]);
        bf0[35] = bf1[35];
        bf0[36] = bf1[36];
        bf0[37] = Btf(-cospi[36], bf1[37], cospi[28], bf1[58]);
        bf0[38] = Btf(-cospi[28], bf1[38], -cospi[36], bf1[57]);
        bf0[39] = bf1[39];
        bf0[40] = bf1[40];
        bf0[41] = Btf(-cospi[20], bf1[41], cospi[44], bf1[54]);
        bf0[42] = Btf(-cospi[44], bf1[42], -cospi[20], bf1[53]);
        bf0[43] = bf1[43];
        bf0[44] = bf1[44];
        bf0[45] = Btf(-cospi[52], bf1[45], cospi[12], bf1[50]);
        bf0[46] = Btf(-cospi[12], bf1[46], -cospi[52], bf1[49]);
        bf0[47] = bf1[47];
        bf0[48] = bf1[48];
        bf0[49] = Btf(-cospi[52], bf1[46], cospi[12], bf1[49]);
        bf0[50] = Btf(cospi[12], bf1[45], cospi[52], bf1[50]);
        bf0[51] = bf1[51];
        bf0[52] = bf1[52];
        bf0[53] = Btf(-cospi[20], bf1[42], cospi[44], bf1[53]);
        bf0[54] = Btf(cospi[44], bf1[41], cospi[20], bf1[54]);
        bf0[55] = bf1[55];
        bf0[56] = bf1[56];
        bf0[57] = Btf(-cospi[36], bf1[38], cospi[28], bf1[57]);
        bf0[58] = Btf(cospi[28], bf1[37], cospi[36], bf1[58]);
        bf0[59] = bf1[59];
        bf0[60] = bf1[60];
        bf0[61] = Btf(-cospi[4], bf1[34], cospi[60], bf1[61]);
        bf0[62] = Btf(cospi[60], bf1[33], cospi[4], bf1[62]);
        bf0[63] = bf1[63];

        // Stage 5.
        for (int i = 0; i < 4; i++) bf1[i] = bf0[i];
        bf1[4] = Btf(cospi[56], bf0[4], -cospi[8], bf0[7]);
        bf1[5] = Btf(cospi[24], bf0[5], -cospi[40], bf0[6]);
        bf1[6] = Btf(cospi[40], bf0[5], cospi[24], bf0[6]);
        bf1[7] = Btf(cospi[8], bf0[4], cospi[56], bf0[7]);
        bf1[8] = bf0[8] + bf0[9];
        bf1[9] = bf0[8] - bf0[9];
        bf1[10] = -bf0[10] + bf0[11];
        bf1[11] = bf0[10] + bf0[11];
        bf1[12] = bf0[12] + bf0[13];
        bf1[13] = bf0[12] - bf0[13];
        bf1[14] = -bf0[14] + bf0[15];
        bf1[15] = bf0[14] + bf0[15];
        bf1[16] = bf0[16];
        bf1[17] = Btf(-cospi[8], bf0[17], cospi[56], bf0[30]);
        bf1[18] = Btf(-cospi[56], bf0[18], -cospi[8], bf0[29]);
        bf1[19] = bf0[19];
        bf1[20] = bf0[20];
        bf1[21] = Btf(-cospi[40], bf0[21], cospi[24], bf0[26]);
        bf1[22] = Btf(-cospi[24], bf0[22], -cospi[40], bf0[25]);
        bf1[23] = bf0[23];
        bf1[24] = bf0[24];
        bf1[25] = Btf(-cospi[40], bf0[22], cospi[24], bf0[25]);
        bf1[26] = Btf(cospi[24], bf0[21], cospi[40], bf0[26]);
        bf1[27] = bf0[27];
        bf1[28] = bf0[28];
        bf1[29] = Btf(-cospi[8], bf0[18], cospi[56], bf0[29]);
        bf1[30] = Btf(cospi[56], bf0[17], cospi[8], bf0[30]);
        bf1[31] = bf0[31];
        bf1[32] = bf0[32] + bf0[35];
