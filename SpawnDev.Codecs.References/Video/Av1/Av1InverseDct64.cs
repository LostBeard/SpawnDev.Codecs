namespace SpawnDev.Codecs.Video.Av1;

/// <summary>AV1 64-point inverse DCT (1D building block).</summary>
public static class Av1InverseDct64
{
    /// <summary>libaom default cos_bit for the inverse 64-point DCT.</summary>
    public const int DefaultCosBit = 12;

    /// <summary>
    /// 64-point inverse DCT. Mirrors libaom <c>av1_idct64</c>.
    /// </summary>
    public static void Transform(ReadOnlySpan<int> input, Span<int> output, int cosBit = DefaultCosBit)
    {
        if (input.Length < 64) throw new ArgumentException("input must have 64 entries", nameof(input));
        if (output.Length < 64) throw new ArgumentException("output must have 64 entries", nameof(output));
        if (cosBit < 10 || cosBit > 13) throw new ArgumentOutOfRangeException(nameof(cosBit), "must be in [10, 13]");

        int Btf(int w0, int in0, int w1, int in1) =>
            Av1ForwardDct4.HalfBtf(w0, in0, w1, in1, cosBit);
        var cospi = Av1ForwardDct4.CospiArr(cosBit);

        Span<int> bf0 = stackalloc int[64];
        Span<int> bf1 = stackalloc int[64];

        // Stage 1: input bit-reverse permutation.
        bf1[0] = input[0]; bf1[1] = input[32]; bf1[2] = input[16]; bf1[3] = input[48];
        bf1[4] = input[8]; bf1[5] = input[40]; bf1[6] = input[24]; bf1[7] = input[56];
        bf1[8] = input[4]; bf1[9] = input[36]; bf1[10] = input[20]; bf1[11] = input[52];
        bf1[12] = input[12]; bf1[13] = input[44]; bf1[14] = input[28]; bf1[15] = input[60];
        bf1[16] = input[2]; bf1[17] = input[34]; bf1[18] = input[18]; bf1[19] = input[50];
        bf1[20] = input[10]; bf1[21] = input[42]; bf1[22] = input[26]; bf1[23] = input[58];
        bf1[24] = input[6]; bf1[25] = input[38]; bf1[26] = input[22]; bf1[27] = input[54];
        bf1[28] = input[14]; bf1[29] = input[46]; bf1[30] = input[30]; bf1[31] = input[62];
        bf1[32] = input[1]; bf1[33] = input[33]; bf1[34] = input[17]; bf1[35] = input[49];
        bf1[36] = input[9]; bf1[37] = input[41]; bf1[38] = input[25]; bf1[39] = input[57];
        bf1[40] = input[5]; bf1[41] = input[37]; bf1[42] = input[21]; bf1[43] = input[53];
        bf1[44] = input[13]; bf1[45] = input[45]; bf1[46] = input[29]; bf1[47] = input[61];
        bf1[48] = input[3]; bf1[49] = input[35]; bf1[50] = input[19]; bf1[51] = input[51];
        bf1[52] = input[11]; bf1[53] = input[43]; bf1[54] = input[27]; bf1[55] = input[59];
        bf1[56] = input[7]; bf1[57] = input[39]; bf1[58] = input[23]; bf1[59] = input[55];
        bf1[60] = input[15]; bf1[61] = input[47]; bf1[62] = input[31]; bf1[63] = input[63];

        // Stage 2: rotate top quarter (32..63).
        for (int i = 0; i < 32; i++) bf0[i] = bf1[i];
        bf0[32] = Btf(cospi[63], bf1[32], -cospi[1], bf1[63]);
        bf0[33] = Btf(cospi[31], bf1[33], -cospi[33], bf1[62]);
        bf0[34] = Btf(cospi[47], bf1[34], -cospi[17], bf1[61]);
        bf0[35] = Btf(cospi[15], bf1[35], -cospi[49], bf1[60]);
        bf0[36] = Btf(cospi[55], bf1[36], -cospi[9], bf1[59]);
        bf0[37] = Btf(cospi[23], bf1[37], -cospi[41], bf1[58]);
        bf0[38] = Btf(cospi[39], bf1[38], -cospi[25], bf1[57]);
        bf0[39] = Btf(cospi[7], bf1[39], -cospi[57], bf1[56]);
        bf0[40] = Btf(cospi[59], bf1[40], -cospi[5], bf1[55]);
        bf0[41] = Btf(cospi[27], bf1[41], -cospi[37], bf1[54]);
        bf0[42] = Btf(cospi[43], bf1[42], -cospi[21], bf1[53]);
        bf0[43] = Btf(cospi[11], bf1[43], -cospi[53], bf1[52]);
        bf0[44] = Btf(cospi[51], bf1[44], -cospi[13], bf1[51]);
        bf0[45] = Btf(cospi[19], bf1[45], -cospi[45], bf1[50]);
        bf0[46] = Btf(cospi[35], bf1[46], -cospi[29], bf1[49]);
        bf0[47] = Btf(cospi[3], bf1[47], -cospi[61], bf1[48]);
        bf0[48] = Btf(cospi[61], bf1[47], cospi[3], bf1[48]);
        bf0[49] = Btf(cospi[29], bf1[46], cospi[35], bf1[49]);
        bf0[50] = Btf(cospi[45], bf1[45], cospi[19], bf1[50]);
        bf0[51] = Btf(cospi[13], bf1[44], cospi[51], bf1[51]);
        bf0[52] = Btf(cospi[53], bf1[43], cospi[11], bf1[52]);
        bf0[53] = Btf(cospi[21], bf1[42], cospi[43], bf1[53]);
        bf0[54] = Btf(cospi[37], bf1[41], cospi[27], bf1[54]);
        bf0[55] = Btf(cospi[5], bf1[40], cospi[59], bf1[55]);
        bf0[56] = Btf(cospi[57], bf1[39], cospi[7], bf1[56]);
        bf0[57] = Btf(cospi[25], bf1[38], cospi[39], bf1[57]);
        bf0[58] = Btf(cospi[41], bf1[37], cospi[23], bf1[58]);
        bf0[59] = Btf(cospi[9], bf1[36], cospi[55], bf1[59]);
        bf0[60] = Btf(cospi[49], bf1[35], cospi[15], bf1[60]);
        bf0[61] = Btf(cospi[17], bf1[34], cospi[47], bf1[61]);
        bf0[62] = Btf(cospi[33], bf1[33], cospi[31], bf1[62]);
        bf0[63] = Btf(cospi[1], bf1[32], cospi[63], bf1[63]);

        // Stage 3.
        for (int i = 0; i < 16; i++) bf1[i] = bf0[i];
        bf1[16] = Btf(cospi[62], bf0[16], -cospi[2], bf0[31]);
        bf1[17] = Btf(cospi[30], bf0[17], -cospi[34], bf0[30]);
        bf1[18] = Btf(cospi[46], bf0[18], -cospi[18], bf0[29]);
        bf1[19] = Btf(cospi[14], bf0[19], -cospi[50], bf0[28]);
        bf1[20] = Btf(cospi[54], bf0[20], -cospi[10], bf0[27]);
        bf1[21] = Btf(cospi[22], bf0[21], -cospi[42], bf0[26]);
        bf1[22] = Btf(cospi[38], bf0[22], -cospi[26], bf0[25]);
        bf1[23] = Btf(cospi[6], bf0[23], -cospi[58], bf0[24]);
        bf1[24] = Btf(cospi[58], bf0[23], cospi[6], bf0[24]);
        bf1[25] = Btf(cospi[26], bf0[22], cospi[38], bf0[25]);
        bf1[26] = Btf(cospi[42], bf0[21], cospi[22], bf0[26]);
        bf1[27] = Btf(cospi[10], bf0[20], cospi[54], bf0[27]);
        bf1[28] = Btf(cospi[50], bf0[19], cospi[14], bf0[28]);
